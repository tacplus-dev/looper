[[ "$h" == "$(sed 's/<repo>/alpha/' "$FIX/templates/HISTORY.md")"$'\n'"- $today looper issue Issue 4 (#4, $(cat "$FIX/fix"))" ]] || fail "HISTORY.md: $h"
